//Вам дан массив целых чисел height длиной n. Нарисованы n вертикальные линии,
//конечные точки которых равны и .ith(i, 0)(i, height[i])
//Найдите две прямые, которые вместе с осью x образуют контейнер,
//так что в контейнере содержится наибольшее количество воды.
//Верните максимальное количество воды, которое может вместить контейнер .
//Обратите внимание , что контейнер нельзя наклонять.

//Входные данные: высота = [1,8,6,2,5,4,8,3,7]
// Выходные данные: 49
// Пояснение: Вертикальные линии на изображении
//выше представлены массивом [1,8,6,2,5,4,8,3,7].
//В этом случае максимальная площадь воды (синяя секция), которую может вместить контейнер, составляет 49.

func MaxArea11(height []int) int {
	maxArea := 0

	l := 0
	r := len(height) - 1

	for l < r {
		minHeight := min(height[l], height[r])
		sum := minHeight * (r - l)

		if sum > maxArea {
			maxArea = sum
		}

		for l < r && height[l] <= minHeight {
			l++
		}
		for l < r && height[r] <= minHeight {
			r--
		}
	}
	return maxArea
}
